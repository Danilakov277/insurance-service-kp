def _clean(x):
    for a, b in [("225.00", "225,00"), ("3000.00", "3 000,00"), ("47000.00", "47 000,00"), ("112.50", "112,50"),
                 ("1979.52", "1 979,52"), ("50000×0,005×0,90", "50 000 × 0,005 × 0,90"), ("12 мес.", "12 месяцев"),
                 ("4 записей", "4 записи"), ("напр. Страхование квартиры: 1973.0 %", "например, страхование квартиры: "
                 "1 973,0 %"), ("2025–2026 гг.", "2025–2026 годы"), ("—", "–")]:
        x = x.replace(a, b)
    return x


